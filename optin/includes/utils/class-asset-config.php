<?php
/**
 * Builds and enqueues shared script and style configuration for plugin contexts.
 *
 * @package Optin
 */

namespace OPTN\Includes\Utils;

defined( 'ABSPATH' ) || exit;

/**
 * Builds shared script/style metadata and applies WordPress runtime compatibility.
 * Asset URLs, handles, dependencies, content hashes, translations, and styles stay
 * in one filterable configuration so admin and frontend enqueues use the same rules.
 */
class AssetConfig {
	/**
	 * Builds default asset metadata for an admin, frontend, or runtime entry.
	 * It reads generated dependency metadata, rewrites the React runtime handle for
	 * older WordPress versions, derives versions from file hashes, and adds the
	 * context's styles and translation path.
	 *
	 * @param string $context Asset context: admin, frontend, or jsx-runtime.
	 * @return array Script, style, and translation configuration.
	 */
	public static function defaults( string $context ): array {
		$slug  = 'optin';
		$entry = $context === 'admin' ? 'build/admin/index' : 'build/fe/index';
		if ( $context === 'jsx-runtime' ) {
			$entry = 'assets/js/react-jsx-runtime'; }
		$metadata     = is_file( OPTN_DIR . $entry . '.asset.php' ) ? include OPTN_DIR . $entry . '.asset.php' : array();
		$metadata     = is_array( $metadata ) ? $metadata : array();
		$dependencies = $context === 'jsx-runtime' ? array( 'react' ) : ( $metadata['dependencies'] ?? array() );
		if ( ! is_array( $dependencies ) ) {
			$dependencies = array(); }
		global $wp_version;
		if ( version_compare( $wp_version, '6.6', '<' ) ) {
			$dependencies = array_map(
				function ( $handle ) use ( $slug ) {
						return $handle === 'react-jsx-runtime' ? $slug . '-jsx-runtime' : $handle;
				},
				$dependencies
			); }
		// Reuse file versions within this request; configuration and extension filters stay live.
		static $versions = array();

		$version = static function ( $file ) use ( &$versions ) {
			if ( ! isset( $versions[ $file ] ) ) {
				$versions[ $file ] = is_file( OPTN_DIR . $file ) ? substr( hash_file( 'sha256', OPTN_DIR . $file ), 0, 16 ) : OPTN_VERSION;
			}
			return $versions[ $file ];
		};
		$config  = array(
			'script' => array(
				'handle'       => $slug . '-' . ( $context === 'jsx-runtime' ? 'jsx-runtime' : $context . '-js' ),
				'src'          => OPTN_URL . $entry . '.js',
				'dependencies' => $dependencies,
				'version'      => $version( $entry . '.js' ),
				'in_footer'    => true,
			),
			'styles' => array(),
		);
		$styles  = $context === 'admin' ? array( 'admin/css/wowoptin-admin.min.css', 'build/admin/style-index' . ( is_rtl() ? '-rtl' : '' ) . '.css' ) : ( $context === 'frontend' ? array( 'frontend/css/wowoptin-public.min.css' ) : array() );
		foreach ( $styles as $index => $file ) {
			$config['styles'][] = array(
				'handle'       => $slug . '-' . $context . '-css-' . $index,
				'src'          => OPTN_URL . $file,
				'dependencies' => array(),
				'version'      => $version( $file ),
			); }
		$config['translations'] = array(
			'domain' => 'optin',
			'path'   => OPTN_DIR . 'languages',
		);
		return $config;
	}
	/**
	 * Gets the default asset configuration after the shared extension filter runs.
	 *
	 * @param string $context Asset context passed to defaults() and the filter.
	 * @return array Filtered script, style, and translation configuration.
	 */
	public static function get( string $context ): array {
		return apply_filters( 'optn_asset_config', self::defaults( $context ), $context ); }
	/**
	 * Enqueues the configured script, styles, and script translations for a context.
	 * On WordPress versions before 6.6, it first enqueues the compatibility React
	 * runtime for admin and frontend scripts.
	 *
	 * @param string $context Asset context to enqueue.
	 * @return array Configuration used for the enqueue operations.
	 */
	public static function enqueue( string $context ): array {
		global $wp_version;
		if ( $context !== 'jsx-runtime' && version_compare( $wp_version, '6.6', '<' ) ) {
			self::enqueue( 'jsx-runtime' ); }
		$config = self::get( $context );
		$script = $config['script'];
		wp_enqueue_script( $script['handle'], $script['src'], $script['dependencies'], $script['version'], $script['in_footer'] );
		$translations = $config['translations'] ?? array(
			'domain' => 'optin',
			'path'   => OPTN_DIR . 'languages',
		);
		wp_set_script_translations( $script['handle'], $translations['domain'], $translations['path'] );
		foreach ( $config['styles'] as $style ) {
			wp_enqueue_style( $style['handle'], $style['src'], $style['dependencies'], $style['version'] ); }
		return $config;
	}
	/**
	 * Adds cache-bypass attributes to tags for Optin's scripts.
	 * Existing no-minify tags and unrelated handles pass through unchanged.
	 *
	 * @param string $tag    Script tag generated by WordPress.
	 * @param string $handle Enqueued script handle associated with the tag.
	 * @return string Original or cache-protected script tag.
	 */
	public static function cache_attributes( $tag, $handle ) {
		if ( strpos( $tag, 'data-no-minify=' ) !== false ) {
			return $tag; }
		foreach ( array( 'admin', 'frontend', 'jsx-runtime' ) as $context ) {
			if ( self::get( $context )['script']['handle'] === $handle ) {
				return str_replace( '<script ', '<script data-nowprocket data-no-minify="1" ', $tag ); }
		}
		return $tag;
	}
}
